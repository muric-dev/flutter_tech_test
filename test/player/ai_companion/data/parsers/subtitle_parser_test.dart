import 'package:cabina/common/errors/exceptions.dart';
import 'package:cabina/player/ai_companion/data/parsers/subtitle_parser.dart';
import 'package:cabina/player/ai_companion/models/transcript.dart';
import 'package:cabina/player/ai_companion/models/transcript_segment.dart';
import 'package:flutter_test/flutter_test.dart';

const _srt = '''
1\r
00:00:00,000 --> 00:00:12,500\r
♪ ♪\r
\r
2\r
00:00:12,500 --> 00:00:15,200\r
Welcome back to <i>Night Shift</i>.\r
\r
3\r
00:00:15,200 --> 00:00:40,000\r
♪\r
\r
4\r
00:00:40,000 --> 00:00:44,840\r
Today we talk about
the last lighthouse keepers.\r
\r
5\r
00:00:44,840 --> 00:01:10,000\r
♪\r
''';

const _vtt = '''
WEBVTT
Kind: captions

NOTE Generated by the host's editor.

00:00.000 --> 00:12.500
[Music]

intro-2
00:00:12.500 --> 00:00:15.200 align:start
<v Ana>Welcome back to Night Shift.</v>

00:00:15.200 --> 00:00:40.000
[Music]

00:00:40.000 --> 00:00:44.840
Today we talk about
the last lighthouse keepers.

00:00:44.840 --> 00:01:10.000
[Music]
''';

const _cues = [
  TranscriptSegment(
    start: Duration(seconds: 12, milliseconds: 500),
    text: 'Welcome back to Night Shift.',
  ),
  TranscriptSegment(
    start: Duration(seconds: 15, milliseconds: 200),
    text: '♪',
    isMusic: true,
  ),
  TranscriptSegment(
    start: Duration(seconds: 40),
    text: 'Today we talk about the last lighthouse keepers.',
  ),
];

void main() {
  const parser = SubtitleParser();

  group('SubtitleParser', () {
    test(
      'GIVEN an SRT file with ♪ cues at the start, middle and end THEN '
      'returns the cues in order with their starts, only the middle ♪ as '
      'music',
      () {
        expect(
          parser.parse(_srt),
          const Transcript(
            source: TranscriptSource.rss,
            segments: _cues,
            duration: Duration(minutes: 1, seconds: 10),
          ),
        );
      },
    );

    test('GIVEN a VTT file THEN returns the same cues', () {
      expect(parser.parse(_vtt).segments, _cues);
    });

    test('GIVEN an SRT with only music cues THEN returns no segment', () {
      const musicOnly = '''
1
00:00:00,000 --> 00:01:30,000
♪ ♪

2
00:01:30,000 --> 00:03:00,000
[Music]
''';

      expect(parser.parse(musicOnly).segments, isEmpty);
    });

    test(
      'GIVEN an HTML page served at the transcript URL THEN throws '
      'FeedParseException',
      () {
        expect(
          () => parser.parse(
            '<!DOCTYPE html><html><body><h1>Transcript</h1></body></html>',
          ),
          throwsA(isA<FeedParseException>()),
        );
      },
    );
  });
}
